@dataclass
class LawEvent:
    """Event yielded during pipeline execution."""
    law: Law
    type: str
    data: Any = None
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class GenerationTrace:
    """Complete trace of a generation — the foundation of self-evolution."""
    task: str = ""
    domain: str = ""
    spec: str = ""
    spec_issues: list[str] = field(default_factory=list)
    test_code: str = ""
    impl_code: str = ""
    candidates: list[dict[str, Any]] = field(default_factory=list)
    test_results: dict[str, Any] = field(default_factory=dict)
    review_findings: list[str] = field(default_factory=list)
    security_findings: list[str] = field(default_factory=list)
    trust_score: float = 0.0
    trust_level: str = ""
    recommendation: str = ""
    lessons_learned: list[str] = field(default_factory=list)
    new_skills: list[dict[str, Any]] = field(default_factory=list)
    laws_completed: list[str] = field(default_factory=list)
    duration_ms: float = 0.0
    success: bool = False
    trace_id: str = ""


class NineLawsPipeline:
    """The definitive code generation methodology — 5 years ahead.

    Nine laws, executed in order. Each law addresses a failure mode
    discovered through rigorous research. Together they form a system
    that gets BETTER with every generation — self-evolving, not static.
    """

    def __init__(
        self,
        gateway: Any = None,
        tools: Any = None,
        memory: Any = None,
        arbiter: Any = None,
    ) -> None:
        self._gateway = gateway
        self._tools = tools
        self._memory = memory
        self._arbiter = arbiter
        # Model tiers
        self._thinker = "deepseek-v4-pro"      # Deep reasoning, code generation
        self._worker = "deepseek-v4-flash"      # Fast reviews, audits, parsing
        # Skill registry — self-evolving across sessions
        self._skill_registry: list[dict[str, Any]] = []
        self._trace_log: list[GenerationTrace] = []

    # ═══════════════════════════════════════════════════════════
    # MAIN PIPELINE
    # ═══════════════════════════════════════════════════════════

    async def generate(
        self,
        task: str,
        *,
        max_candidates: int = 3,
        max_retries: int = 3,
    ) -> AsyncGenerator[LawEvent, None]:
        """Execute all Nine Laws in order.

        The order is NON-NEGOTIABLE — each law builds on the previous.
        """
        t0 = time.time()
        trace = GenerationTrace(
            task=task,
            domain=self._classify_domain(task),
            trace_id=hashlib.sha256(f"{task}{t0}".encode()).hexdigest()[:12],
        )

        # ═════════════════════════════════════════════════════
        # LAW 1: INTENT PRECISION
        # "Ambiguity in specification is the root of all bugs."
        # Source: Speciune ICSE 2026 + Royce 1970
        # ═════════════════════════════════════════════════════
        yield LawEvent(Law.INTENT, "progress", "Generating precise specification...")
        spec, issues = await self._law_intent(task)
        trace.spec = spec
        trace.spec_issues = issues
        trace.laws_completed.append(Law.INTENT.value)

        yield LawEvent(Law.INTENT, "output", spec)
        if issues:
            for i in issues[:5]:
                yield LawEvent(Law.INTENT, "output", f"⚠ {i}")
        yield LawEvent(Law.INTENT, "progress",
                      f"Spec: {len(spec)} chars, {len(issues)} issues detected")

        # ═════════════════════════════════════════════════════
        # LAW 2: SELF-EVOLVING MEMORY
        # "Every generation makes the next one better."
        # Source: Socratic-SWE 2026 + My Multi-Temporal Learning
        # ═════════════════════════════════════════════════════
        yield LawEvent(Law.LEARN, "progress", "Loading relevant skills from registry...")
        relevant_skills = await self._law_learn(task, trace.domain)
        trace.laws_completed.append(Law.LEARN.value)

        if relevant_skills:
            yield LawEvent(Law.LEARN, "progress",
                          f"Loaded {len(relevant_skills)} relevant skills from past generations")
            for s in relevant_skills[:3]:
                yield LawEvent(Law.LEARN, "output",
                              f"📦 {s.get('name', '?')}: {s.get('lesson', '')[:80]}")

        # ═════════════════════════════════════════════════════
        # LAW 3: BEHAVIORAL PLANNING
        # "Plan the work, then work the plan."
        # Source: SEAlign ICSE 2026 Distinguished + Structured Programming
        # ═════════════════════════════════════════════════════
        yield LawEvent(Law.PLAN, "progress", "Planning tool-use strategy and decision points...")
        plan = await self._law_plan(task, spec, relevant_skills)
        trace.laws_completed.append(Law.PLAN.value)

        yield LawEvent(Law.PLAN, "progress",
                      f"Strategy: {plan.get('strategy', '?')} | "
                      f"Tools: {len(plan.get('tools_needed', []))} | "
                      f"Decision points: {len(plan.get('decision_points', []))}")

        # ═════════════════════════════════════════════════════
        # LAW 4: TEST-DRIVEN DEVELOPMENT
        # "If you can't test it, you don't understand it."
        # Source: Beck 1999, 25+ years of evidence
        # ═════════════════════════════════════════════════════
        yield LawEvent(Law.TEST, "progress", "Writing tests BEFORE implementation...")

        # Generate test contracts (formal pre/post conditions)
        contracts = await self._law_generate_contracts(task, spec, plan)
        if contracts:
            yield LawEvent(Law.TEST, "progress",
                          f"Formal contracts: {len(contracts)} pre/post conditions")

        tests = await self._law_tests(task, spec, contracts, plan)
        trace.test_code = tests
        trace.laws_completed.append(Law.TEST.value)

        yield LawEvent(Law.TEST, "output", tests)
        yield LawEvent(Law.TEST, "progress", f"Tests: {len(tests)} chars")

        # ═════════════════════════════════════════════════════
        # LAW 5: STRUCTURE-AWARE GENERATION
        # "Code is structure, not text. Operate on the AST."
        # Source: CodeStruct ACL 2026 + Compiler theory
        # ═════════════════════════════════════════════════════
        yield LawEvent(Law.CODE, "progress",
                      f"Generating {max_candidates} candidates with beam search...")

        candidates = await self._law_code(
            task, spec, tests, contracts, plan, max_candidates
        )
        trace.candidates = candidates

        if not candidates:
            yield LawEvent(Law.FAILED, "error",
                          "No valid candidates generated — API may have returned empty results. "
                          "Check DEEPSEEK_API_KEY and network connectivity.")
            return

        # Select best candidate
        best = max(candidates, key=lambda c: c.get("score", 0))
        trace.impl_code = best["code"]
        trace.laws_completed.append(Law.CODE.value)

        yield LawEvent(Law.CODE, "output", best["code"])
        yield LawEvent(Law.CODE, "progress",
                      f"Best candidate score: {best.get('score', 0):.1f}/100 "
                      f"(from {len(candidates)} candidates)")

        # ═════════════════════════════════════════════════════
        # LAW 6: MULTI-METHOD VERIFICATION
        # "One reviewer is an opinion. Three is a consensus."
        # Source: Agentic Proving 2026 + 56 CVEs Q1 2026
        # ═════════════════════════════════════════════════════
        yield LawEvent(Law.VERIFY, "progress",
                      "Running multi-method verification (tests + review + security + formal)...")

        # 6a: Test execution with auto-fix
        test_result = await self._verify_tests(best["code"], tests)
        trace.test_results = test_result

        if not test_result.get("passed"):
            yield LawEvent(Law.VERIFY, "progress", "Tests FAILED — auto-fixing code...")
            for retry in range(max_retries):
                fixed = await self._auto_fix(best["code"], tests, test_result)
                test_result = await self._verify_tests(fixed, tests)
                if test_result.get("passed"):
                    best["code"] = fixed
                    trace.impl_code = fixed
                    yield LawEvent(Law.VERIFY, "progress",
                                  f"Tests PASSED after {retry+1} code fix(es)")
                    break
            else:
                # 代码修复全部失败 → 尝试修复测试代码（测试可能有bug）
                yield LawEvent(Law.VERIFY, "progress", "Code fixes failed — trying test fixes...")
                fixed_tests = await self._auto_fix_tests(tests, best["code"], test_result)
                test_result = await self._verify_tests(best["code"], fixed_tests)
                if test_result.get("passed"):
                    trace.test_code = fixed_tests
                    yield LawEvent(Law.VERIFY, "progress", "Tests PASSED after fixing test code")
                else:
                    yield LawEvent(Law.VERIFY, "output",
                                  "Tests still failing after code+test fixes — see review")
        else:
            yield LawEvent(Law.VERIFY, "progress", "All tests PASSED")

        # 6b: Code quality review (independent model)
        review_findings = await self._review_code(best["code"], spec)
        trace.review_findings = review_findings
        yield LawEvent(Law.VERIFY, "progress",
                      f"Code review: {len(review_findings)} issues")

        # 6c: Security audit (independent model)
        sec_findings = await self._security_audit(best["code"])
        trace.security_findings = sec_findings
        yield LawEvent(Law.VERIFY, "progress",
                      f"Security audit: {len(sec_findings)} issues")

        # 6d: Formal contract verification (if contracts exist)
        if contracts:
            formal_ok = await self._verify_contracts(best["code"], contracts)
            yield LawEvent(Law.VERIFY, "progress",
                          f"Formal verification: {'PASSED' if formal_ok else 'partial'}")

        trace.laws_completed.append(Law.VERIFY.value)

        # ═════════════════════════════════════════════════════
        # LAW 7: CALIBRATED TRUST
        # "Trust is earned, not assumed. Measure it."
        # Source: 46% distrust statistic + My innovation
        # ═════════════════════════════════════════════════════
        yield LawEvent(Law.TRUST, "progress", "Calculating calibrated trust score...")

        trust = self._law_trust(trace)
        trace.trust_score = trust["score"]
        trace.trust_level = trust["level"]
        trace.recommendation = trust["recommendation"]
        trace.success = trust["score"] >= 40
        trace.laws_completed.append(Law.TRUST.value)

        yield LawEvent(Law.TRUST, "output", trust)

        # ═════════════════════════════════════════════════════
        # LAW 8: MULTI-TEMPORAL LEARNING
        # "Knowledge must compound across minutes, days, and years."
        # Source: My innovation — 4-tier memory architecture
        # ═════════════════════════════════════════════════════
        yield LawEvent(Law.COMPOUND, "progress",
                      "Compounding knowledge across time scales...")

        lessons, new_skills = await self._law_compound(trace)
        trace.lessons_learned = lessons
        trace.new_skills = new_skills
        trace.laws_completed.append(Law.COMPOUND.value)

        yield LawEvent(Law.COMPOUND, "progress",
                      f"Learned {len(lessons)} lessons, "
                      f"created {len(new_skills)} new skills")

        # ═════════════════════════════════════════════════════
        # LAW 9: HUMAN AUTHORITY
        # "The human is always the ultimate decision-maker."
        # Source: Agile Manifesto + ConstitutionalArbiter
        # ═════════════════════════════════════════════════════
        trace.total_duration_ms = (time.time() - t0) * 1000
        trace.laws_completed.append(Law.HUMAN.value)

        yield LawEvent(Law.HUMAN, "progress", "Presenting for human judgment...")
        yield LawEvent(Law.HUMAN, "output", {
            "trace_id": trace.trace_id,
            "success": trace.success,
            "laws": trace.laws_completed,
            "duration_ms": trace.total_duration_ms,
            "code_chars": len(trace.impl_code),
            "test_chars": len(trace.test_code),
            "candidates": len(trace.candidates),
            "trust_score": trace.trust_score,
            "trust_level": trace.trust_level,
            "recommendation": trace.recommendation,
            "spec_issues": len(trace.spec_issues),
            "review_issues": len(trace.review_findings),
            "security_issues": len(trace.security_findings),
            "lessons_learned": len(trace.lessons_learned),
            "new_skills": len(trace.new_skills),
        })

        # Store trace for self-evolution
        self._trace_log.append(trace)
        yield LawEvent(Law.DONE, "done", trace)

    # ═══════════════════════════════════════════════════════════
    # LAW 1: INTENT PRECISION
    # ═══════════════════════════════════════════════════════════

    async def _law_intent(self, task: str) -> tuple[str, list[str]]:
        """Architect generates spec → Critic detects misalignment.

        Speciune (ICSE 2026): dual-agent detection achieves 29.6% Pass@1 improvement.
        """
        if not self._gateway:
            return task, ["No gateway"]

        # Agent A: Architect
        arch_prompt = f"""You are a senior software architect. Generate a precise technical specification.

TASK: {task}

INCLUDE with ABSOLUTE PRECISION:
1. FILES — exact paths to create/modify
2. INTERFACES — complete function signatures with types, class APIs with methods
3. DATA TYPES — all custom types, their fields, constraints
4. BEHAVIOR — what each function does, pre/post conditions
5. ERROR STATES — every possible error, how to handle each
6. EDGE CASES — empty/null/invalid input, boundary values, concurrency
7. DEPENDENCIES — what this depends on (libraries, services, files)

ETERNAL PRINCIPLES:
{ETERNAL_PRINCIPLES}

Be PRECISE. Ambiguity = bugs. Output in clean markdown."""

        spec = await self._ask(self._thinker, arch_prompt)

        # Agent B: Critic
        critic_prompt = f"""You are a specification reviewer. Find ALL issues.

TASK: {task}

SPECIFICATION:
{spec[:4000]}

CHECK (be ruthless):
1. Ambiguity — anything interpretable multiple ways
2. Missing edge cases — what's NOT covered
3. Type gaps — untyped or under-typed interfaces
4. Security blind spots — what could be exploited
5. Missing error handling — what error states are ignored
6. Over-engineering — is this simpler than it needs to be?

Output: "ISSUE: <description>" per issue. "NO_ISSUES" if perfect."""

        critic = await self._ask(self._worker, critic_prompt)
        issues = [l[6:].strip() for l in critic.split("\n")
                  if l.strip().upper().startswith("ISSUE:")]

        return spec, issues

    # ═══════════════════════════════════════════════════════════
    # LAW 2: SELF-EVOLVING MEMORY
    # ═══════════════════════════════════════════════════════════

    async def _law_learn(
        self, task: str, domain: str,
    ) -> list[dict[str, Any]]:
        """Load relevant skills from self-evolving registry + 5-layer memory.

        Socratic-SWE (2026): agents using trace-derived skills improve 7.8% on SWE-bench.
        My extension: skills also come from cross-session Hexis memory.
        """
        skills = []

        # From self-evolving registry (in-session)
        for s in self._skill_registry:
            if s.get("domain") == domain or any(
                kw in task.lower() for kw in s.get("keywords", [])
            ):
                skills.append(s)

        # From 5-layer Hexis memory (cross-session — includes regular chat code gen)
        if self._memory:
            try:
                ctx = self._memory.get_context(query=task, top_k=8)
                for m in ctx.get("relevant_memories", []):
                    meta = m.get("metadata", {}) if isinstance(m.get("metadata"), dict) else {}
                    # 接受 code_generation 类型和 pattern_type 类型
                    if meta.get("type") == "code_generation" or "pattern_type" in meta:
                        skills.append({
                            "name": f"memory:{m.get('level', '?')}",
                            "lesson": m.get("content", "")[:150],
                            "source": "hexis",
                            "keywords": meta.get("keywords", task.lower().split()[:5]),
                        })
            except Exception:
                pass

        return skills[:10]

    # ═══════════════════════════════════════════════════════════
    # LAW 3: BEHAVIORAL PLANNING
    # ═══════════════════════════════════════════════════════════

    async def _law_plan(
        self, task: str, spec: str, skills: list[dict[str, Any]],
    ) -> dict[str, Any]:
        """Plan tool-use with decision points and anti-loop guards.

        SEAlign (ICSE 2026 Distinguished): behavioral alignment
        improves real-task solving from 2.8% → 21.8%.
        """
        skill_context = ""
        if skills:
            skill_context = "RELEVANT PAST KNOWLEDGE:\n" + "\n".join(
                f"- {s.get('lesson', '')[:120]}" for s in skills[:5]
            )

        prompt = f"""Plan the EXACT execution strategy for this coding task.

TASK: {task}
{skill_context}

OUTPUT valid JSON:
{{
  "strategy": "create_new|modify_existing|incremental_refactor|bug_fix",
  "files_to_touch": ["path1", "path2"],
  "tools_needed": ["tool1", "tool2"],
  "decision_points": [
    {{"step": 1, "check": "what to verify", "if_pass": "next action", "if_fail": "recovery action"}}
  ],
  "anti_loop_guard": "condition that means we're stuck",
  "max_turns": 8,
  "critical_success_criteria": "how we know we're COMPLETELY done"
}}

Output ONLY the JSON. No other text."""

        resp = await self._ask(self._worker, prompt)
        try:
            start = resp.find("{")
            end = resp.rfind("}") + 1
            if start >= 0 and end > start:
                return json.loads(resp[start:end])
        except Exception:
            pass

        return {
            "strategy": "create_new",
            "files_to_touch": [],
            "tools_needed": ["file_write", "sandbox_execute"],
            "decision_points": [],
            "anti_loop_guard": "Same error 3 times → ask human",
            "max_turns": 8,
            "critical_success_criteria": "All tests pass + code review clean",
        }

    # ═══════════════════════════════════════════════════════════
    # LAW 4: CONTRACTS + TESTS
    # ═══════════════════════════════════════════════════════════

    async def _law_generate_contracts(
        self, task: str, spec: str, plan: dict[str, Any],
    ) -> str:
        """Generate formal pre/post condition contracts.

        Agentic Proving (2026): 98.8% spec generation with verifier-in-the-loop.
        This is the bridge between testing and formal verification.
        """
        prompt = f"""Generate formal contracts (pre/post conditions) for this specification.

TASK: {task}
SPEC: {spec[:4000]}

For each function/endpoint, write:
- PRE: what must be true before calling
- POST: what must be true after calling
- INVARIANTS: what must always be true

Use Python assertions or docstring contracts. These will be checked at verification time.

Output ONLY the contract code."""

        return await self._ask(self._thinker, prompt)

    async def _law_tests(
        self, task: str, spec: str, contracts: str, plan: dict[str, Any],
    ) -> str:
        """Write comprehensive tests BEFORE implementation. Non-negotiable."""
        prompt = f"""Write COMPREHENSIVE tests BEFORE the implementation exists.

TASK: {task}
SPEC: {spec[:4000]}
CONTRACTS (must be verified):
{contracts[:1000]}

WRITE:
1. Unit tests for every function — normal + edge + error paths
2. Integration tests for multi-component flows
3. Contract tests — verify all pre/post conditions
4. Property-based tests — random inputs should never crash

Use pytest with fixtures and parametrize. Coverage target: >90%.

Tests MUST fail against empty implementation — this is TDD red phase.

Output ONLY the test code."""

        return await self._ask(self._thinker, prompt)

