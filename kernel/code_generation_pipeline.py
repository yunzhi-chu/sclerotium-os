    async def _ask(self, model: str, prompt: str) -> str:
        """Call LLM via gateway with proper capabilities — no hardcoded limits."""
        import asyncio
        if not self._gateway:
            return ""

        # 使用模型能力数据库，不做硬编码限制
        from gateways.model_capabilities import get_capability
        cap = get_capability(model, "deepseek")
        max_tok = cap.max_output_tokens if cap else 384_000

        def _sync_call():
            import urllib.request, json as _json, os
            # 使用网关配置的provider，不硬编码URL
            try:
                provider = "deepseek"
                api_key = os.environ.get("DEEPSEEK_API_KEY", "")
                base_url = "https://api.deepseek.com/v1"
                # 尝试从网关获取路由
                if hasattr(self._gateway, 'get_best_route'):
                    try:
                        route = self._gateway.get_best_route()
                        if route:
                            provider = route.provider
                            base_url = route.base_url
                            api_key = route.api_key or api_key
                    except Exception:
                        pass

                headers = {"Content-Type": "application/json"}
                if api_key and api_key != "ollama":
                    headers["Authorization"] = f"Bearer {api_key}"
                body = {"model": model, "messages": [{"role":"user","content": prompt}],
                        "max_tokens": max_tok, "temperature": 0.6}
                req = urllib.request.Request(f"{base_url}/chat/completions",
                    data=_json.dumps(body).encode("utf-8"), headers=headers, method="POST")
                with urllib.request.urlopen(req, timeout=300) as resp:
                    data = _json.loads(resp.read())
                    content = data.get("choices", [{}])[0].get("message", {}).get("content", "")
                    if not content:
                        raise ValueError("Empty response from API")
                    return content
            except Exception as e:
                # 重试一次
                try:
                    import time; time.sleep(2)
                    with urllib.request.urlopen(req, timeout=300) as resp:
                        data = _json.loads(resp.read())
                        return data.get("choices", [{}])[0].get("message", {}).get("content", "")
                except Exception:
                    return ""

        return await asyncio.to_thread(_sync_call)

    def _classify_domain(self, task: str) -> str:
        tl = task.lower()
        if any(k in tl for k in ["api", "endpoint", "rest", "fastapi", "flask", "django", "graphql"]):
            return "api"
        if any(k in tl for k in ["react", "vue", "component", "ui", "frontend", "css", "html"]):
            return "frontend"
        if any(k in tl for k in ["database", "sql", "migration", "model", "schema", "orm"]):
            return "database"
        if any(k in tl for k in ["pipeline", "data", "etl", "processing", "stream", "batch"]):
            return "data"
        if any(k in tl for k in ["test", "testing", "coverage", "mock", "stub"]):
            return "testing"
