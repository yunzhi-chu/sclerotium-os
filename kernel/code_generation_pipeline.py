    async def _verify_tests(
        self, code: str, tests: str,
    ) -> dict[str, Any]:
        """Execute tests against generated code in an isolated temp file."""
        result = {"passed": False, "failures": [], "output": "", "stderr": ""}
        if not self._tools:
            return result

        # 写临时文件执行——比拼字符串更可靠
        import tempfile, os, subprocess
        tmpdir = tempfile.mkdtemp(prefix="sclerotium_verify_")
        try:
            code_path = os.path.join(tmpdir, "code.py")
            test_path = os.path.join(tmpdir, "test_code.py")
            with open(code_path, "w", encoding="utf-8") as f:
                f.write(code)
            with open(test_path, "w", encoding="utf-8") as f:
                f.write(tests)

            # 使用pytest运行（如果可用），否则python -m pytest
            try:
                r = subprocess.run(
                    ["python", "-m", "pytest", test_path, "-v", "--tb=short"],
                    capture_output=True, text=True, timeout=60,
                    cwd=tmpdir,
                )
                result["output"] = r.stdout[:2000]
                result["stderr"] = r.stderr[:2000]
                result["passed"] = r.returncode == 0
                if not result["passed"]:
                    result["failures"] = [
                        line for line in (r.stdout + r.stderr).split("\n")
                        if "FAIL" in line or "Error" in line or "error" in line
                    ][:10]
            except FileNotFoundError:
                # pytest not available — fallback to python直接运行
                r = subprocess.run(
                    ["python", test_path],
                    capture_output=True, text=True, timeout=60,
                    cwd=tmpdir,
                )
                result["output"] = r.stdout[:2000]
                result["stderr"] = r.stderr[:2000]
                result["passed"] = r.returncode == 0
                if not result["passed"]:
                    result["failures"] = [(r.stderr or r.stdout)[:500]]
        except Exception as e:
            result["failures"] = [str(e)[:500]]
        finally:
            import shutil
            shutil.rmtree(tmpdir, ignore_errors=True)
        return result

