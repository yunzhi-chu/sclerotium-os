    def _law_trust(self, trace: GenerationTrace) -> dict[str, Any]:
        """Calculate calibrated trust based on ALL evidence.

        My innovation: trust is NOT binary. It's a continuous score
        with clear thresholds and actionable recommendations.
        """
        score = 0.0

        # Test results (strongest signal)
        if trace.test_results.get("passed"):
            score += 30
        elif any("fail" in str(f).lower() for f in trace.test_results.get("failures", [])):
            score += 5  # Failed but we know why

        # Candidate diversity (more candidates = more exploration)
        if len(trace.candidates) >= 3:
            score += 5
        if len(trace.candidates) >= 5:
            score += 5

        # Best candidate score
        best_score = max((c.get("score", 0) for c in trace.candidates), default=0)
        score += best_score * 0.2

        # Review findings (fewer = better)
        if len(trace.review_findings) == 0:
            score += 15
        elif len(trace.review_findings) <= 2:
            score += 10
        elif len(trace.review_findings) <= 5:
            score += 5

        # Security findings (fewer = better)
        if len(trace.security_findings) == 0:
            score += 20
        elif len(trace.security_findings) <= 2:
            score += 10

        # Spec quality
        if len(trace.spec_issues) == 0:
            score += 10
        elif len(trace.spec_issues) <= 2:
            score += 5

        # Skill relevance
        if any("memory" in s.get("source", "") for s in getattr(self, '_skill_registry', [])):
            score += 5  # Had relevant past experience

        score = max(0, min(100, score))

        if score >= 80:
            level = "HIGH — Production-ready. Standard review sufficient."
            rec = "Code is safe to deploy. Review findings for awareness."
        elif score >= 55:
            level = "MEDIUM — Review carefully before deployment."
            rec = "Address review findings. Run integration tests."
        elif score >= 30:
            level = "LOW — Multiple concerns. Manual review REQUIRED."
            rec = "Do NOT deploy without human review. Address all findings."
        else:
            level = "CRITICAL — Do not use. Fundamental issues detected."
            rec = "Restart with clearer specification or smaller scope."

        return {"score": score, "level": level, "recommendation": rec}

