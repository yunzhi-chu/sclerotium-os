@dataclass
class TaskProfile:
    """5-dimensional task analysis profile.

    Each dimension is scored 0.0–1.0 and guides architecture generation.
    """

    reasoning_depth: float = 0.5       # Required reasoning complexity
    tool_dependency: float = 0.5       # External tool usage intensity
    time_sensitivity: float = 0.5      # Latency urgency
    collaboration_need: float = 0.5    # Multi-agent coordination required
    security_requirement: float = 0.5  # Safety / compliance level

    @property
    def vector(self) -> np.ndarray:
        return np.array([
            self.reasoning_depth, self.tool_dependency,
            self.time_sensitivity, self.collaboration_need,
            self.security_requirement,
        ])

    @property
    def complexity_score(self) -> float:
        """Aggregate task complexity (0-1)."""
        return float(np.mean(self.vector))


@dataclass
class AgentRole:
    """A role definition in the custom architecture."""

    role_id: str
    role_name: str
    specialization: str  # e.g., "generator", "critic", "executor", "verifier"
    required_skills: list[str] = field(default_factory=list)
    gene_assignments: list[str] = field(default_factory=list)  # gene IDs
    capability_score: float = 0.0
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class CustomArchitecture:
    """A task-specific multi-agent architecture generated by MAS²."""

    architecture_id: str
    task_description: str
    task_profile: TaskProfile
    roles: list[AgentRole] = field(default_factory=list)
    topology: str = "hierarchical"  # sequential, parallel, hierarchical, hybrid
    communication_protocol: str = "message_passing"
    estimated_quality: float = 0.0
    estimated_cost_usd: float = 0.0
    estimated_latency_ms: float = 0.0
    generation_metadata: dict[str, Any] = field(default_factory=dict)
    timestamp: float = field(default_factory=time.time)

    @property
    def role_count(self) -> int:
        return len(self.roles)


@dataclass
class ArchitectureBenchmark:
    """Benchmark comparison between custom and baseline architectures."""

    custom_architecture_id: str
    baseline_name: str
    custom_quality: float = 0.0
    baseline_quality: float = 0.0
    custom_cost: float = 0.0
    baseline_cost: float = 0.0
    custom_latency: float = 0.0
    baseline_latency: float = 0.0
    quality_improvement_pct: float = 0.0
    cost_reduction_pct: float = 0.0
    latency_reduction_ms: float = 0.0
    samples_evaluated: int = 50
    timestamp: float = field(default_factory=time.time)


