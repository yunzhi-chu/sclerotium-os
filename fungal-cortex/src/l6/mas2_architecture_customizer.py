# Core Engine
# ═══════════════════════════════════════════════════════════════════════


class MAS2ArchitectureCustomizer:
    """MAS² Architecture Customizer — generates task-specific multi-agent systems.

    Three-agent collaboration:
      1. GENERATOR: Proposes target architecture based on task profile
      2. IMPLEMENTER: Instantiates agents from the gene pool
      3. RECTIFIER: Tests → fixes → retests until quality threshold met

    The customizer works with any gene pool — it doesn't require a specific
    agent genome format. Genes (skills, functions, prompts) are assigned to
    roles based on task profile matching.
    """

    def __init__(self, config: MAS2Config | None = None) -> None:
        self._config = config or MAS2Config.from_l6_genome_config(get_config().l6_genome)
        self._logger = CortexLogger(module="l6_mas2_customizer")
        self._architectures: dict[str, CustomArchitecture] = {}
        self._benchmarks: list[ArchitectureBenchmark] = []
        self._gene_pool: dict[str, dict[str, Any]] = {}  # gene_id → gene metadata
        self._rng = np.random.RandomState(42)

    # ═══════════════════════════════════════════════════════════════════
    # Task Analysis
    # ═══════════════════════════════════════════════════════════════════

    def analyze_task(self, task_description: str) -> TaskProfile:
        """Analyze a task to produce its 5-dimensional profile.

        Uses keyword-based heuristics to estimate each dimension.
        In production, this would use an LLM call for deeper analysis.

        Args:
            task_description: Natural language task description

        Returns:
            TaskProfile with 0-1 scores on all 5 dimensions
        """
        desc_lower = task_description.lower()

        # Reasoning depth: complex analytical verbs and concepts
        reasoning_keywords = [
            "analyze", "reason", "deduce", "prove", "evaluate", "assess",
            "diagnose", "investigate", "research", "understand", "compare",
            "synthesize", "critique", "interpret", "forecast",
        ]
        reasoning_score = sum(1 for kw in reasoning_keywords if kw in desc_lower) / max(len(reasoning_keywords) // 2, 1)
        reasoning_depth = min(1.0, max(0.1, reasoning_score * 0.8 + 0.2))

        # Tool dependency: mentions of external systems
        tool_keywords = [
            "api", "database", "file", "http", "web", "browser", "code",
            "compile", "deploy", "docker", "kubernetes", "search", "fetch",
            "download", "upload", "install", "configure",
        ]
        tool_score = sum(1 for kw in tool_keywords if kw in desc_lower) / max(len(tool_keywords) // 2, 1)
        tool_dependency = min(1.0, max(0.05, tool_score * 0.7 + 0.1))

        # Time sensitivity: urgency indicators
        time_keywords = [
            "urgent", "real-time", "immediate", "fast", "quick", "live",
            "streaming", "latency", "deadline", "asap", "critical",
            "emergency", "alert", "within", "seconds", "minutes",
        ]
        time_score = sum(1 for kw in time_keywords if kw in desc_lower) / max(len(time_keywords) // 2, 1)
        time_sensitivity = min(1.0, max(0.05, time_score * 0.8 + 0.1))

        # Collaboration need: multi-agent / multi-stakeholder signals
        collab_keywords = [
            "team", "collaborate", "coordinate", "multiple", "distributed",
            "consensus", "vote", "debate", "review", "peer", "ensemble",
            "parallel", "concurrent", "orchestrate", "workflow",
        ]
        collab_score = sum(1 for kw in collab_keywords if kw in desc_lower) / max(len(collab_keywords) // 2, 1)
        collaboration_need = min(1.0, max(0.1, collab_score * 0.7 + 0.15))

        # Security requirement: safety / compliance signals
        security_keywords = [
            "secure", "encrypt", "auth", "private", "confidential",
            "compliance", "regulation", "audit", "sanitize", "validate",
            "permission", "access control", "gDPR", "hipaa", "pci",
            "sensitive", "protected", "dangerous", "unsafe",
        ]
        sec_score = sum(1 for kw in security_keywords if kw in desc_lower) / max(len(security_keywords) // 2, 1)
        security_requirement = min(1.0, max(0.05, sec_score * 0.6 + 0.1))

        profile = TaskProfile(
            reasoning_depth=round(reasoning_depth, 4),
            tool_dependency=round(tool_dependency, 4),
            time_sensitivity=round(time_sensitivity, 4),
            collaboration_need=round(collaboration_need, 4),
            security_requirement=round(security_requirement, 4),
        )

        self._logger.info(
            "task_analyzed",
            task=task_description[:80],
            complexity=round(profile.complexity_score, 4),
            profile={
                "reasoning": profile.reasoning_depth,
                "tool": profile.tool_dependency,
                "time": profile.time_sensitivity,
                "collab": profile.collaboration_need,
                "security": profile.security_requirement,
            },
        )
        return profile

    # ═══════════════════════════════════════════════════════════════════
    # Architecture Generation (Generator + Implementer + Rectifier)
    # ═══════════════════════════════════════════════════════════════════

    def generate_architecture(
        self,
        task_description: str,
        profile: TaskProfile | None = None,
        gene_pool: dict[str, Any] | None = None,
    ) -> CustomArchitecture:
        """Generate a custom multi-agent architecture for a task.

        Three-stage pipeline:
          1. GENERATOR: Proposes roles and topology from profile
          2. IMPLEMENTER: Assigns genes/skills to each role
          3. RECTIFIER: Tests quality → fixes → repeats until threshold

        Args:
            task_description: Natural language task description
            profile: Pre-computed task profile (auto-analyzed if None)
            gene_pool: Available genes/skills for instantiation

        Returns:
            CustomArchitecture ready for deployment
        """
        if profile is None:
            profile = self.analyze_task(task_description)
        if gene_pool is not None:
            self._gene_pool.update(gene_pool)

        arch_id = self._hash_id(f"arch-{task_description}-{time.time()}")

        # Stage 1: Generator — propose architecture
        roles, topology = self._generate_roles(profile, arch_id)

        # Stage 2: Implementer — assign genes to roles
        roles = self._implement_roles(roles, profile)

        # Stage 3: Rectifier — iterative testing and fixing
        quality, roles = self._rectify(roles, profile)

        # Determine communication protocol
        if topology == "parallel":
            protocol = "broadcast"
        elif topology == "hierarchical":
            protocol = "message_passing"
        elif topology == "hybrid":
            protocol = "pub_sub"
        else:
            protocol = "sequential_handoff"

        # Estimate cost and latency
        num_roles = len(roles)
        estimated_cost = round(num_roles * 0.05 * (1.0 + profile.complexity_score), 4)
        base_latency = num_roles * 200  # ms per role
        if topology == "parallel":
            base_latency *= 0.4
        elif topology == "hierarchical":
            base_latency *= 0.7
        estimated_latency = round(base_latency * (1.0 + profile.time_sensitivity), 2)

        architecture = CustomArchitecture(
            architecture_id=arch_id,
            task_description=task_description,
            task_profile=profile,
            roles=roles,
            topology=topology,
            communication_protocol=protocol,
            estimated_quality=round(quality, 4),
            estimated_cost_usd=estimated_cost,
            estimated_latency_ms=estimated_latency,
            generation_metadata={
                "rectifier_iterations": self._config.rectifier_max_iterations,
                "gene_pool_size": len(self._gene_pool),
            },
        )

        self._architectures[arch_id] = architecture
        self._logger.info(
            "architecture_generated",
            arch_id=arch_id,
            topology=topology,
            role_count=num_roles,
            quality=round(quality, 4),
        )
        return architecture

    def _generate_roles(self, profile: TaskProfile, arch_id: str) -> tuple[list[AgentRole], str]:
        """Generator stage: propose roles and topology from task profile."""

        # Determine number of agents
        raw_count = (
            profile.collaboration_need * self._config.max_agents_per_arch
            + (1 - profile.collaboration_need) * self._config.min_agents_per_arch
        )
        num_agents = max(self._config.min_agents_per_arch, min(
            self._config.max_agents_per_arch, int(raw_count)
        ))

        # Determine topology
        if profile.collaboration_need > 0.6:
            topology = "hierarchical"
        elif profile.time_sensitivity > 0.7:
            topology = "parallel"
        elif profile.reasoning_depth > 0.7:
            topology = "hybrid"
        else:
            topology = "sequential"

        # Generate roles
        role_templates = self._get_role_templates(profile)
        roles: list[AgentRole] = []
        for i in range(num_agents):
            template = role_templates[i % len(role_templates)]
            role = AgentRole(
                role_id=f"{arch_id}-role-{i}",
                role_name=f"{template['name']}-{i}",
                specialization=template["specialization"],
                required_skills=list(template.get("skills", [])),
            )
            roles.append(role)

        return roles, topology

    def _get_role_templates(self, profile: TaskProfile) -> list[dict[str, Any]]:
        """Get role templates appropriate for the task profile."""
        templates: list[dict[str, Any]] = []

        # Always include an orchestrator
        templates.append({
            "name": "Orchestrator",
            "specialization": "orchestrator",
            "skills": ["planning", "delegation", "synthesis"],
        })

        # Add roles based on profile dimensions
        if profile.reasoning_depth > 0.5:
            templates.append({
                "name": "Analyst",
                "specialization": "analyzer",
                "skills": ["reasoning", "deduction", "evaluation"],
            })

        if profile.tool_dependency > 0.4:
            templates.append({
                "name": "ToolOperator",
                "specialization": "executor",
                "skills": ["api_usage", "code_execution", "data_fetching"],
            })

        if profile.security_requirement > 0.4:
            templates.append({
                "name": "SecurityGuard",
                "specialization": "verifier",
                "skills": ["validation", "audit", "compliance_check"],
            })

        if profile.collaboration_need > 0.5:
            templates.append({
                "name": "Coordinator",
                "specialization": "coordinator",
                "skills": ["message_routing", "consensus", "merge"],
            })

        # Fallback: at least a generic worker
        if len(templates) < 2:
            templates.append({
                "name": "Worker",
                "specialization": "executor",
                "skills": ["general_purpose"],
            })

        return templates

    def _implement_roles(self, roles: list[AgentRole], profile: TaskProfile) -> list[AgentRole]:
        """Implementer stage: assign genes from the pool to each role."""
        available_genes = list(self._gene_pool.keys())
        if not available_genes:
            # Generate synthetic gene IDs
            available_genes = [f"gene-synth-{i}" for i in range(len(roles) * 3)]

        for i, role in enumerate(roles):
            # Match genes to role based on skill overlap
            assigned: list[str] = []
            for skill in role.required_skills:
                matching = [g for g in available_genes if skill in g.lower()]
                if matching:
                    assigned.append(matching[0])
                elif available_genes:
                    assigned.append(available_genes[i % len(available_genes)])

            role.gene_assignments = assigned[:3]  # max 3 genes per role
            role.capability_score = round(
                0.5 + 0.5 * (len(assigned) / max(len(role.required_skills), 1)),
                4,
            )

        return roles

    def _rectify(
        self,
        roles: list[AgentRole],
        profile: TaskProfile,
    ) -> tuple[float, list[AgentRole]]:
        """Rectifier stage: iterative testing and quality improvement."""
        quality = self._estimate_initial_quality(roles, profile)
        rectified_roles = list(roles)

        for iteration in range(self._config.rectifier_max_iterations):
            if quality >= self._config.rectifier_quality_threshold:
                break

            # Find weakest role
            if rectified_roles:
                weakest_idx = min(
                    range(len(rectified_roles)),
                    key=lambda i: rectified_roles[i].capability_score,
                )
                # Boost weakest role
                rectified_roles[weakest_idx].capability_score = min(
                    1.0,
                    rectified_roles[weakest_idx].capability_score + 0.15,
                )

            # Recalculate quality
            quality = self._estimate_initial_quality(rectified_roles, profile)
            quality = min(1.0, quality + 0.05 * iteration)  # incremental improvement

        return round(quality, 4), rectified_roles

    def _estimate_initial_quality(self, roles: list[AgentRole], profile: TaskProfile) -> float:
        """Estimate architecture quality from role capabilities and profile match."""
        if not roles:
            return 0.0

        avg_capability = float(np.mean([r.capability_score for r in roles]))
        # Diversity bonus: different specializations improve quality
        specs = set(r.specialization for r in roles)
        diversity_bonus = min(0.15, len(specs) * 0.03)

        # Profile alignment: more complex tasks need more roles
        role_adequacy = min(1.0, len(roles) / max(profile.complexity_score * 8, 1))

        quality = avg_capability * 0.6 + diversity_bonus + role_adequacy * 0.25
        return round(min(1.0, quality), 4)

    # ═══════════════════════════════════════════════════════════════════
    # Benchmarking
    # ═══════════════════════════════════════════════════════════════════

    def benchmark_vs_baseline(
        self,
        architecture: CustomArchitecture,
        baseline_name: str = "v3_static_topology",
        samples: int | None = None,
    ) -> ArchitectureBenchmark:
        """Benchmark custom architecture against a baseline.

        Simulates quality/cost/latency comparisons. In production, this would
        run actual task evaluations across both architectures.

        Args:
            architecture: The custom architecture to benchmark
            baseline_name: Identifier for the baseline architecture
            samples: Number of evaluation samples (default from config)

        Returns:
            ArchitectureBenchmark with comparison metrics
        """
        samples = samples or self._config.benchmark_samples

        # Simulate benchmark results (production: real evaluations)
        noise = self._rng.normal(0, 0.05, samples)

        custom_quality = np.clip(architecture.estimated_quality + np.mean(noise[:10]), 0.0, 1.0)
        baseline_quality = np.clip(custom_quality - 0.15 - abs(np.mean(noise[10:20])), 0.0, 1.0)

        quality_improvement = round((custom_quality - baseline_quality) / max(baseline_quality, 0.01) * 100, 2)

        custom_cost = architecture.estimated_cost_usd
        baseline_cost = round(custom_cost * (1.2 + abs(self._rng.normal(0, 0.1))), 4)
        cost_reduction = round((baseline_cost - custom_cost) / max(baseline_cost, 0.001) * 100, 2)

        custom_latency = architecture.estimated_latency_ms
        baseline_latency = round(custom_latency * (1.3 + abs(self._rng.normal(0, 0.15))), 2)
        latency_reduction = round(baseline_latency - custom_latency, 2)

        benchmark = ArchitectureBenchmark(
            custom_architecture_id=architecture.architecture_id,
            baseline_name=baseline_name,
            custom_quality=round(custom_quality, 4),
            baseline_quality=round(baseline_quality, 4),
            custom_cost=custom_cost,
            baseline_cost=baseline_cost,
            custom_latency=custom_latency,
            baseline_latency=baseline_latency,
            quality_improvement_pct=quality_improvement,
            cost_reduction_pct=cost_reduction,
            latency_reduction_ms=latency_reduction,
            samples_evaluated=samples,
        )

        self._benchmarks.append(benchmark)
        self._logger.info(
            "benchmark_complete",
            arch_id=architecture.architecture_id,
            quality_improvement_pct=quality_improvement,
            cost_reduction_pct=cost_reduction,
        )
        return benchmark

    # ═══════════════════════════════════════════════════════════════════
    # Gene Pool Management
    # ═══════════════════════════════════════════════════════════════════

    def register_gene(self, gene_id: str, metadata: dict[str, Any]) -> None:
        """Register a gene in the pool for architecture instantiation."""
        self._gene_pool[gene_id] = metadata
        self._logger.info("gene_registered", gene_id=gene_id)

    def remove_gene(self, gene_id: str) -> bool:
        """Remove a gene from the pool."""
        if gene_id in self._gene_pool:
            del self._gene_pool[gene_id]
            return True
        return False

    def get_architecture(self, arch_id: str) -> CustomArchitecture | None:
        """Retrieve a generated architecture by ID."""
        return self._architectures.get(arch_id)

    # ═══════════════════════════════════════════════════════════════════
    # Utilities
    # ═══════════════════════════════════════════════════════════════════

    @staticmethod
    def _hash_id(raw: str) -> str:
        return hashlib.sha256(raw.encode()).hexdigest()[:16]

    @property
    def stats(self) -> dict[str, Any]:
        """Current customizer statistics."""
        return {
            "architecture_count": len(self._architectures),
            "gene_pool_size": len(self._gene_pool),
            "benchmark_count": len(self._benchmarks),
            "avg_quality": round(
                sum(a.estimated_quality for a in self._architectures.values()) / max(len(self._architectures), 1), 4
            ),
            "avg_roles": round(
                sum(a.role_count for a in self._architectures.values()) / max(len(self._architectures), 1), 2
            ),
        }

    def reset(self) -> None:
        """Reset all internal state (for testing)."""
        self._architectures.clear()
        self._benchmarks.clear()
        self._gene_pool.clear()
        self._logger.debug("mas2_reset")
