@dataclass
class MAS2Config:
    """Runtime configuration for MAS² Architecture Customizer."""

    min_agents_per_arch: int = 2
    max_agents_per_arch: int = 10
    rectifier_max_iterations: int = 5
    rectifier_quality_threshold: float = 0.85
    benchmark_samples: int = 50

    @classmethod
    def from_l6_genome_config(cls, cfg: L6GenomeConfig) -> MAS2Config:
        return cls(
            min_agents_per_arch=cfg.mas2_min_agents_per_arch,
            max_agents_per_arch=cfg.mas2_max_agents_per_arch,
            rectifier_max_iterations=cfg.mas2_rectifier_max_iterations,
            rectifier_quality_threshold=cfg.mas2_rectifier_quality_threshold,
            benchmark_samples=cfg.mas2_benchmark_samples,
        )


