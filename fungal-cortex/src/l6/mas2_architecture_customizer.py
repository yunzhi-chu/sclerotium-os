"""MAS² Architecture Customizer — 多Agent系统自主架构定制.

Biological Metaphor:
  Stem cell differentiation — the same genome produces different cell types
  (neuron, muscle, blood, bone) by activating/inhibiting different gene
  combinations. Similarly, MAS² generates task-specific multi-agent
  architectures from the same agent genome pool.

  MAS² (ICLR 2026) core insight:
  Don't use a single multi-agent architecture for all tasks. Instead,
  dynamically generate a CUSTOM architecture per task using three
  collaborating agents: Generator → Implementer → Rectifier.

  Results: +19.6% SOTA on deep research + code generation.
  Cross-backbone generalization: +15.1% with unseen LLMs.
  Pareto-frontier consistently optimal on cost-performance tradeoff.

Key Innovation (v4.0):
  TaskProfile analysis maps tasks to 5 dimensions (reasoning depth, tool needs,
  time constraints, collaboration complexity, security level). Generator proposes
  target architecture, Implementer instantiates from gene pool, Rectifier tests
  and fixes in iterative cycles until quality threshold met.

References:
  - MAS² (ICLR 2026): Multi-Agent System Self-customization
  - Stem cell differentiation analogy: Waddington landscape
"""

